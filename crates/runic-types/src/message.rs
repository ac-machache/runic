    #[test]
    fn test_msg_id_is_server_assigned_uuid() {
        // Every constructor must stamp a server-side UUID — never trust the
        // LLM-provided ID as the primary key.
        let a = Message::user("hello");
        let b = Message::user("hello");
        assert_ne!(a.msg_id, b.msg_id, "msg_id must be unique per message");
        // Must parse as a valid UUID v4.
        let parsed = uuid::Uuid::parse_str(&a.msg_id).expect("msg_id must be a valid UUID");
        assert_eq!(parsed.get_version_num(), 4, "msg_id must be UUID v4");
        // Provider id defaults to None.
        assert!(a.provider_msg_id.is_none());
    }

