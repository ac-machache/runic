//! LLM conversation message types.

use serde::{Deserialize, Serialize};

/// Generate a fresh server-assigned message ID.
///
/// Used as the serde default for `Message::msg_id` so that messages persisted
/// before this field existed are stamped with a stable UUID on first load.
/// New messages built via `Message::user`, `Message::assistant`, etc. also
/// receive a fresh server-generated UUID rather than trusting any
/// LLM-provided identifier (which can collide across sessions or be reused).
fn new_msg_id() -> String {
    uuid::Uuid::new_v4().to_string()
}

/// A message in an LLM conversation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Message {
    /// Server-assigned unique message ID (UUID v4).
    ///
    /// Always generated by OpenFang at message creation time. LLM providers'
    /// own `id` fields are unreliable (different formats per provider, can
    /// collide across sessions, sometimes absent), so we never use them as the
    /// primary key. The provider-supplied ID, when present, is preserved in
    /// `provider_msg_id` for debugging only.
    ///
    /// Old sessions on disk that predate this field will deserialize with a
    /// freshly-generated UUID — they had no stable ID before, so this is a
    /// strict improvement.
    #[serde(default = "new_msg_id")]
    pub msg_id: String,
    /// Optional LLM-provided message identifier (e.g. Anthropic `msg_abc...`,
    /// OpenAI `chatcmpl-...`). Preserved for debugging/correlation only —
    /// never used as the primary identifier.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub provider_msg_id: Option<String>,
    /// The role of the sender.
    pub role: Role,
    /// The content of the message.
    pub content: MessageContent,
}

/// The role of a message sender in an LLM conversation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    /// System prompt.
    System,
    /// Human user.
    #[default]
    User,
    /// AI assistant.
    Assistant,
}

/// Content of a message — can be simple text or structured blocks.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum MessageContent {
    /// Simple text content.
    Text(String),
    /// Structured content blocks.
    Blocks(Vec<ContentBlock>),
}

impl Default for MessageContent {
    fn default() -> Self {
        MessageContent::Text(String::new())
    }
}

impl Default for Message {
    fn default() -> Self {
        Self {
            msg_id: new_msg_id(),
            provider_msg_id: None,
            role: Role::User,
            content: MessageContent::Text(String::new()),
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum Source {
    Inline(#[serde(with = "inline_bytes")] Vec<u8>),
    Url(String),
    Stored(String),
    Uploaded { file_id: String, provider: String },
}

mod inline_bytes {
    use base64::Engine;
    use serde::{Deserializer, Serializer, de};

    pub fn serialize<S: Serializer>(bytes: &[u8], serializer: S) -> Result<S::Ok, S::Error> {
        match serializer.is_human_readable() {
            true => {
                serializer.serialize_str(&base64::engine::general_purpose::STANDARD.encode(bytes))
            }
            false => serializer.serialize_bytes(bytes),
        }
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(deserializer: D) -> Result<Vec<u8>, D::Error> {
        struct Bytes;

        impl<'de> de::Visitor<'de> for Bytes {
            type Value = Vec<u8>;

            fn expecting(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {
                formatter.write_str("base64 text or raw bytes")
            }

            fn visit_str<E: de::Error>(self, text: &str) -> Result<Vec<u8>, E> {
                base64::engine::general_purpose::STANDARD
                    .decode(text)
                    .map_err(de::Error::custom)
            }

            fn visit_bytes<E: de::Error>(self, bytes: &[u8]) -> Result<Vec<u8>, E> {
                Ok(bytes.to_vec())
            }

            fn visit_byte_buf<E: de::Error>(self, bytes: Vec<u8>) -> Result<Vec<u8>, E> {
                Ok(bytes)
            }

            fn visit_seq<A: de::SeqAccess<'de>>(self, mut seq: A) -> Result<Vec<u8>, A::Error> {
                let mut bytes = Vec::with_capacity(seq.size_hint().unwrap_or_default());
                while let Some(byte) = seq.next_element()? {
                    bytes.push(byte);
                }
                Ok(bytes)
            }
        }

        deserializer.deserialize_any(Bytes)
    }
}

impl Source {
    pub fn inline(&self) -> Option<&[u8]> {
        match self {
            Source::Inline(bytes) => Some(bytes),
            _ => None,
        }
    }

    pub fn url(&self) -> Option<&str> {
        match self {
            Source::Url(url) => Some(url),
            _ => None,
        }
    }

    pub fn stored(&self) -> Option<&str> {
        match self {
            Source::Stored(id) => Some(id),
            _ => None,
        }
    }

    pub fn uploaded(&self) -> Option<(&str, &str)> {
        match self {
            Source::Uploaded { file_id, provider } => Some((file_id, provider)),
            _ => None,
        }
    }
}

/// A content block within a message.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum ContentBlock {
    /// A text block.
    #[serde(rename = "text")]
    Text {
        /// The text content.
        text: String,
        /// Provider-specific metadata (e.g. Gemini `thoughtSignature`).
        /// Opaque to the core — drivers read/write this to round-trip
        /// fields the provider requires on subsequent requests.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        provider_metadata: Option<serde_json::Value>,
    },
    #[serde(rename = "image")]
    Image {
        media_type: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        filename: Option<String>,
        #[serde(flatten)]
        source: Source,
    },
    #[serde(rename = "file")]
    File {
        media_type: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        filename: Option<String>,
        #[serde(flatten)]
        source: Source,
    },
    /// A tool use request from the assistant.
    #[serde(rename = "tool_use")]
    ToolUse {
        /// Unique ID for this tool use.
        id: String,
        /// The tool name.
        name: String,
        /// The tool input parameters.
        input: serde_json::Value,
        /// Provider-specific metadata (e.g. Gemini `thoughtSignature`).
        /// Opaque to the core — drivers read/write this to round-trip
        /// fields the provider requires on subsequent requests.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        provider_metadata: Option<serde_json::Value>,
    },
    /// A tool result from executing a tool.
    #[serde(rename = "tool_result")]
    ToolResult {
        /// The tool_use ID this result corresponds to.
        tool_use_id: String,
        /// The tool name (for Gemini FunctionResponse). Empty for legacy sessions.
        #[serde(default)]
        tool_name: String,
        /// The result content.
        content: ToolResultPayload,
        /// Whether the tool execution errored.
        is_error: bool,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        provenance: Vec<crate::ProvenanceSource>,
    },
    /// Extended thinking content block (model's reasoning trace).
    ///
    /// Preserved across turns so reasoning models retain state. Anthropic's
    /// extended thinking requires the `signature` to be echoed on resubmission;
    /// other providers (Gemini thought signatures, DeepSeek/Qwen
    /// `reasoning_content`, MiniMax inline `<think>`) round-trip via
    /// `provider_metadata` or by inlining into the assistant message body.
    #[serde(rename = "thinking")]
    Thinking {
        /// The thinking/reasoning text.
        thinking: String,
        /// Provider-issued signature required to resubmit thinking blocks
        /// (Anthropic extended thinking). `None` for providers that don't
        /// emit a signature.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        signature: Option<String>,
        /// Provider-specific metadata (e.g. `{"format": "reasoning_content"}`
        /// or `{"format": "inline_think"}` so the outbound driver knows how
        /// the upstream model originally delivered the reasoning).
        #[serde(default, skip_serializing_if = "Option::is_none")]
        provider_metadata: Option<serde_json::Value>,
    },
    /// Anthropic redacted-thinking block — encrypted reasoning the model
    /// chose to hide. The `data` blob is opaque to us but MUST be echoed
    /// verbatim on subsequent turns, otherwise Anthropic rejects the
    /// resubmitted history. Only emitted by the Anthropic driver.
    #[serde(rename = "redacted_thinking")]
    RedactedThinking {
        /// Opaque encrypted reasoning payload from Anthropic.
        data: String,
    },
    /// Catch-all for unrecognized content block types (forward compatibility).
    #[serde(other)]
    Unknown,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ToolResultPayload {
    Inline(serde_json::Value),
    Artifact {
        id: String,
        preview: String,
        mime: String,
        size: u64,
    },
}

impl ToolResultPayload {
    pub fn inline(value: impl Into<serde_json::Value>) -> Self {
        ToolResultPayload::Inline(value.into())
    }

    pub fn text(&self) -> String {
        match self {
            ToolResultPayload::Inline(serde_json::Value::String(text)) => text.clone(),
            ToolResultPayload::Inline(value) => value.to_string(),
            ToolResultPayload::Artifact {
                id,
                preview,
                mime,
                size,
            } => format!("{preview}\n[full output stored as artifact {id} ({mime}, {size} bytes)]"),
        }
    }

    pub fn text_length(&self) -> usize {
        match self {
            ToolResultPayload::Inline(serde_json::Value::String(text)) => text.len(),
            ToolResultPayload::Inline(value) => value.to_string().len(),
            ToolResultPayload::Artifact { preview, .. } => preview.len(),
        }
    }
}

impl Default for ToolResultPayload {
    fn default() -> Self {
        ToolResultPayload::Inline(serde_json::Value::String(String::new()))
    }
}

impl From<&str> for ToolResultPayload {
    fn from(text: &str) -> Self {
        ToolResultPayload::Inline(serde_json::Value::String(text.to_string()))
    }
}

impl From<String> for ToolResultPayload {
    fn from(text: String) -> Self {
        ToolResultPayload::Inline(serde_json::Value::String(text))
    }
}

impl From<serde_json::Value> for ToolResultPayload {
    fn from(value: serde_json::Value) -> Self {
        ToolResultPayload::Inline(value)
    }
}

/// Allowed image media types.
const ALLOWED_IMAGE_TYPES: &[&str] = &["image/png", "image/jpeg", "image/gif", "image/webp"];

/// Maximum decoded image size (5 MB).
const MAX_IMAGE_BYTES: usize = 5 * 1024 * 1024;

/// Validate an image content block.
///
/// Checks that the media type is an allowed image format and the
/// base64 data doesn't exceed 5 MB when decoded (~7 MB base64).
pub fn validate_image(media_type: &str, data: &str) -> Result<(), String> {
    if !ALLOWED_IMAGE_TYPES.contains(&media_type) {
        return Err(format!(
            "Unsupported image type '{}'. Allowed: {}",
            media_type,
            ALLOWED_IMAGE_TYPES.join(", ")
        ));
    }
    // Base64 encodes 3 bytes into 4 chars, so max base64 len ≈ MAX_IMAGE_BYTES * 4/3
    let max_b64_len = MAX_IMAGE_BYTES * 4 / 3 + 4; // small padding allowance
    if data.len() > max_b64_len {
        return Err(format!(
            "Image too large: {} bytes base64 (max ~{} bytes for {} MB decoded)",
            data.len(),
            max_b64_len,
            MAX_IMAGE_BYTES / (1024 * 1024)
        ));
    }
    Ok(())
}

impl MessageContent {
    /// Create simple text content.
    pub fn text(content: impl Into<String>) -> Self {
        MessageContent::Text(content.into())
    }

    /// Get the total character length of text in this content.
    pub fn text_length(&self) -> usize {
        match self {
            MessageContent::Text(s) => s.len(),
            MessageContent::Blocks(blocks) => blocks
                .iter()
                .map(|b| match b {
                    ContentBlock::Text { text, .. } => text.len(),
                    ContentBlock::ToolResult { content, .. } => content.text_length(),
                    ContentBlock::Thinking { thinking, .. } => thinking.len(),
                    ContentBlock::ToolUse { name, input, .. } => {
                        name.len() + input.to_string().len()
                    }
                    ContentBlock::Image { .. }
                    | ContentBlock::File { .. }
                    | ContentBlock::RedactedThinking { .. }
                    | ContentBlock::Unknown => 0,
                })
                .sum(),
        }
    }

    /// Extract all text content as a single string.
    pub fn text_content(&self) -> String {
        match self {
            MessageContent::Text(s) => s.clone(),
            MessageContent::Blocks(blocks) => blocks
                .iter()
                .filter_map(|b| match b {
                    ContentBlock::Text { text, .. } => Some(text.as_str()),
                    _ => None,
                })
                .collect::<Vec<_>>()
                .join(""),
        }
    }
}

impl Message {
    /// Create a system message.
    pub fn system(content: impl Into<String>) -> Self {
        Self {
            msg_id: new_msg_id(),
            provider_msg_id: None,
            role: Role::System,
            content: MessageContent::Text(content.into()),
        }
    }

    /// Create a user message.
    pub fn user(content: impl Into<String>) -> Self {
        Self {
            msg_id: new_msg_id(),
            provider_msg_id: None,
            role: Role::User,
            content: MessageContent::Text(content.into()),
        }
    }

    /// Create a user message with structured content blocks (e.g. text + images).
    pub fn user_with_blocks(blocks: Vec<ContentBlock>) -> Self {
        Self {
            msg_id: new_msg_id(),
            provider_msg_id: None,
            role: Role::User,
            content: MessageContent::Blocks(blocks),
        }
    }

    /// Create an assistant message.
    pub fn assistant(content: impl Into<String>) -> Self {
        Self {
            msg_id: new_msg_id(),
            provider_msg_id: None,
            role: Role::Assistant,
            content: MessageContent::Text(content.into()),
        }
    }

    /// Create an assistant message with structured content blocks.
    ///
    /// Used to preserve `Thinking` blocks (with signatures and reasoning text)
    /// across persistence so reasoning models retain state between turns.
    pub fn assistant_with_blocks(blocks: Vec<ContentBlock>) -> Self {
        Self {
            msg_id: new_msg_id(),
            provider_msg_id: None,
            role: Role::Assistant,
            content: MessageContent::Blocks(blocks),
        }
    }

    /// Attach a provider-supplied message ID (for debugging only).
    ///
    /// The server-generated `msg_id` remains the primary identifier — this
    /// records what the upstream LLM called the same message so we can
    /// correlate logs/traces with provider dashboards.
    pub fn with_provider_msg_id(mut self, provider_id: impl Into<String>) -> Self {
        self.provider_msg_id = Some(provider_id.into());
        self
    }
}

/// Why the LLM stopped generating.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum StopReason {
    /// The model finished its turn.
    EndTurn,
    /// The model wants to use a tool.
    ToolUse,
    /// The model hit the token limit.
    MaxTokens,
    /// The model hit a stop sequence.
    StopSequence,
}

/// Token usage information from an LLM call.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct TokenUsage {
    /// Tokens used for the input/prompt.
    pub input_tokens: u64,
    /// Tokens generated in the output.
    pub output_tokens: u64,
    #[serde(default)]
    pub cache_read_tokens: u64,
    #[serde(default)]
    pub cache_write_tokens: u64,
}

impl TokenUsage {
    /// Total tokens used.
    pub fn total(&self) -> u64 {
        self.input_tokens + self.output_tokens
    }

    pub fn add(&mut self, other: &TokenUsage) {
        self.input_tokens += other.input_tokens;
        self.output_tokens += other.output_tokens;
        self.cache_read_tokens += other.cache_read_tokens;
        self.cache_write_tokens += other.cache_write_tokens;
    }
}

/// Reply directives extracted from agent output.
///
/// These control how the response is delivered back to the user/channel:
/// - `reply_to`: reply to a specific message ID
/// - `current_session`: reply in the current session
/// - `silent`: suppress the response entirely
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct ReplyDirectives {
    /// Reply to a specific message ID.
    pub reply_to: Option<String>,
    /// Reply in the current session.
    pub current_session: bool,
    /// Suppress the response from being sent.
    pub silent: bool,
}

